// Precomputed fast lookup maps
const skillMap = new Map(appliedSkills.map(s => [s.id, s]));
const certToSkillsMap = new Map();

appliedSkills.forEach(s => {
  s.relatedCerts.forEach(certId => {
    if (!certToSkillsMap.has(certId)) {
      certToSkillsMap.set(certId, []);
    }
    certToSkillsMap.get(certId).push(s);
  });
});

/**
 * Returns all Applied Skills credentials.
 */
export const getAllAppliedSkills = () => appliedSkills;

/**
 * Gets an Applied Skill by its ID.
 */
export const getAppliedSkillById = (id) => skillMap.get(id) || null;

/**
 * Gets all Applied Skills for a specific pillar.
 */
export const getAppliedSkillsByPillar = (pillar) => appliedSkills.filter(s => s.pillar === pillar);

/**
 * Gets all Applied Skills that reinforce a specific role-based certification ID.
 */
export const getAppliedSkillsForCert = (certId) => certToSkillsMap.get(certId) || [];
